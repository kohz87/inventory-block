import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const r4 = fs.readFileSync(`${S}/demo/r4.txt`, 'utf8').replace(/<XP>[\s\S]*?<\/XP>\n?/, '');
const at = (time, lines) => r4.replace('1203, March 3, 09:50 am', time).replace(/<Director>[\s\S]*?<\/Director>/, `<Director>\n${lines}\n</Director>`);
await h.openNarrator('The Narrator - 2026-10-18@13h00m00s000ms');
await h.dock();
await h.turn(at('1203, March 3, 10:00 am', "+ hook Weir Eels — Clear the eels fouling the weir | giver: Lyra | reward: 3 silver\n+ hook Kael's Proof — Bring Kael proof of the wolf | giver: Captain Kael | reward: 4 silver"), 'Anything else here?');
await page.waitForTimeout(2500);
await h.tab('ext:story-director-quests'); await page.waitForTimeout(800);
await ev(() => { const d = document.querySelector('.story-director-fold.is-offered'); if (d) d.open = true; });
const cards = () => ev(() => [...document.querySelectorAll('.is-offered .story-director-record')].map(n => `${n.querySelector('.story-director-record-key')?.textContent} [${n.querySelector('.is-giver')?.textContent ?? '-'}] ${n.querySelector('.story-director-offer-actions')?.textContent.replace(/\s+/g, ' ').trim()}`).join(' | '));
console.log('nsd present:', JSON.stringify(await ev(() => { try { return globalThis.NPCStateDelta?.injectionPreview?.()?.presentNpcs ?? 'no api'; } catch (e) { return 'threw ' + e.message; } })));
console.log('top:', await ev(() => document.querySelector('.story-director-quests .story-director-empty-text')?.textContent));
console.log('cards:', await cards());
await ev(() => [...document.querySelectorAll('.is-offered .story-director-record')].find(x => /Kael/.test(x.textContent))?.querySelector('.story-director-offer-take')?.click());
await page.waitForTimeout(400);
console.log('after take on Kael:', await cards());
await ev(() => [...document.querySelectorAll('.is-offered .story-director-record')].find(x => /Kael/.test(x.textContent))?.querySelector('.story-director-offer-take.is-confirm')?.click());
await page.waitForTimeout(700);
console.log('after confirm:', await cards());
await page.screenshot({ path: `${S}/sd-badge.png` });
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
