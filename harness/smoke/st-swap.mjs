import { open, S } from './demo-common.mjs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const side = file => page.screenshot({ path: `${S}/shots/${file}.png`, clip: { x: 1090, y: 40, width: 350, height: 950 } });
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await ev(async () => {
  const ctx = SillyTavern.getContext();
  ctx.extensionSettings.rpgBattle.activeSkills = 3;
  const i = ctx.chat.findLastIndex(m => !m.is_user && m.mes.includes('Skills: Greater Heal'));
  const m = ctx.chat[i];
  m.mes = m.mes.replace(/(Skills: Greater Heal[^\n]*)/, '$1\nSet aside: Mend (Lv 2, 3/12) | Smite (Lv 1, 0/5)');
  if (m.swipes) m.swipes[m.swipe_id ?? 0] = m.mes;
  await ctx.saveChat(); await ctx.reloadCurrentChat();
});
await page.waitForTimeout(2500);
await h.dock();
await h.tab('ext:rpg-party'); await page.waitForTimeout(800);
const lyra = sel => `.rpg-battle-member-card[data-member-id]:not(.is-you) ${sel}`;
await ev(s => { const c = document.querySelector(s); if (c) c.open = true; }, '.rpg-battle-member-card[data-member-id]:not(.is-you)');
