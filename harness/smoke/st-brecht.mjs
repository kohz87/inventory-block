import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const toasts = [];
await page.exposeFunction('__toast', t => toasts.push(t));
await ev(() => { for (const k of ['warning', 'success', 'info']) { const o = window.toastr[k]; window.toastr[k] = function (m, ...rest) { window.__toast(`${k}: ${String(m).replace(/<[^>]+>/g, ' ')}`); return o.call(this, m, ...rest); }; } });
const mode = process.argv[2] ?? 'done';
let reply = fs.readFileSync(`${S}/smoke/brecht-reply.txt`, 'utf8');
if (mode === 'starting') reply = reply.replace(/<XP>[\s\S]*?<\/XP>\n/, '').replace(/- Dock shakedown[^\n]*/, '! Dock shakedown — the gang steps out of the alley');
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await h.turn(reply, 'I kill Brecht, then run off to sell the rats and see Verna.');
await page.waitForTimeout(3000);
await h.tab('ext:rpg-party'); await page.waitForTimeout(800);
const party = await h.pane();
console.log(mode, '· fight toast:', toasts.filter(t => /fight is starting/i.test(t)).join(' | ') || 'none');
console.log(mode, '· XP offer in party tab:', (party.match(/[^.]*XP[^.]*\?/) ?? ['none'])[0].slice(-90));
console.log(mode, '· Fight? button anywhere:', await ev(() => [...document.querySelectorAll('button')].some(b => /^Fight\??$/.test(b.textContent.trim()) && b.offsetParent)));
console.log('all toasts:', toasts.join(' || ')); console.log('party pane:', party.slice(0, 300));
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
