import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const OUT = `${S}/uiux/commission`;
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const base = fs.readFileSync(`${S}/demo/r3.txt`, 'utf8').replace(/<Encounter>[\s\S]*?<\/Encounter>/, '')
  .replace('Harrowford outskirts | The Old Weir', 'Bluewatch Village | Bone-carver\'s lean-to')
  .replace('Waterskin | 1 | Half full', 'Waterskin | 1 | Half full\n\n[Loot]\nGranary Cellar Rat Tail | 5 | material · AGI, poison\nBrood-Mother Skull | 1 | uncommon material · MDEF');
const inv = () => ev(() => { const c = SillyTavern.getContext(); return (c.chat.at(-1).mes.match(/<Inventory>[\s\S]*?<\/Inventory>/) ?? [''])[0]; });
const pick = t => t.split('\n').filter(l => /Coin|Skull|On Order|Ring/.test(l)).join(' / ');
const trade = async () => { await h.tab('ext:rpg-party'); await page.waitForTimeout(600); await ev(() => document.querySelectorAll('.rpg-battle-page')[1]?.click()); await page.waitForTimeout(800); };
const show = sel => ev(s => document.querySelector(s)?.scrollIntoView({ block: 'start' }), sel);
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await h.turn(base, 'I take the skull to the bone-carver.');
await page.waitForTimeout(2500);
console.log('clock now:', await ev(() => { const c = SillyTavern.getContext(); const a = globalThis.StoryDirector; const t = a?.timeAt(c.chat.length - 1); return `${t} = ${a?.formatTime(t)}`; }));
await trade();
console.log('general store commission hint:', await ev(() => document.querySelector('.rpg-trade-commission-who')?.textContent));
await ev(() => { const p = document.querySelector('.rpg-trade-person'); p.value = 'kind:crafter'; p.dispatchEvent(new Event('change')); });
await page.waitForTimeout(500);
console.log('checkboxes:', await ev(() => document.querySelectorAll('.rpg-trade-tab input[type=checkbox]').length), '· when select:', await ev(() => Boolean(document.querySelector('.rpg-trade-when'))));
await ev(() => { const p = document.querySelector('.rpg-trade-piece'); p.value = 'Skull Ring'; p.dispatchEvent(new Event('input')); p.dispatchEvent(new Event('change')); });
await page.waitForTimeout(400);
await ev(() => [...document.querySelectorAll('.rpg-trade-make .rpg-trade-item')].find(li => /Brood-Mother Skull/.test(li.textContent))?.querySelector('.rpg-trade-pick')?.click());
await page.waitForTimeout(500);
console.log('preview:', await ev(() => document.querySelector('.rpg-trade-preview')?.textContent));
await show('.rpg-trade-make');
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/commission-desktop.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(800);
await trade();
await show('.rpg-trade-make');
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/commission-mobile.png` });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.waitForTimeout(800);
await h.dock().catch(() => {});
await trade();
await ev(() => document.querySelector('.rpg-trade-craft:not([disabled])')?.click());
await page.waitForTimeout(1500);
console.log('after commission:', pick(await inv()));
await trade();
console.log('told:', await ev(() => [...document.querySelectorAll('.rpg-trade-told li')].map(li => li.textContent).join(' | ')));
console.log('handoff:', await ev(() => SillyTavern.getContext().chatMetadata.rpgBattle?.trade?.handoff ?? 'none'));
console.log('order row:', await ev(() => [...document.querySelectorAll('.rpg-trade-orders .rpg-trade-item')].map(li => `${li.querySelector('.rpg-trade-item-name').textContent} | collect=${Boolean(li.querySelector('.rpg-trade-collect'))} | ${li.querySelector('.rpg-trade-ready')?.textContent ?? ''}`).join(' / ')));
await show('.rpg-trade-orders');
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/order-desktop.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(800);
await trade();
await show('.rpg-trade-orders');
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/order-mobile.png` });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.waitForTimeout(800);
await h.dock().catch(() => {});
// Days later in the story: the ring is ready to collect.
const later = (await inv()).length ? base.replace('1203, March 3, 09:30 am', '1203, March 9, 10:00 am').replace(/<Inventory>[\s\S]*?<\/Inventory>/, await inv()) : base;
await h.turn(later, 'Days later, I go back to the lean-to.');
await page.waitForTimeout(2500);
console.log('clock later:', await ev(() => { const c = SillyTavern.getContext(); const a = globalThis.StoryDirector; return a?.formatTime(a?.timeAt(c.chat.length - 1)); }));
await trade();
console.log('order row later:', await ev(() => [...document.querySelectorAll('.rpg-trade-orders .rpg-trade-item')].map(li => `${li.querySelector('.rpg-trade-item-name').textContent} | collect=${Boolean(li.querySelector('.rpg-trade-collect'))}`).join(' / ')));
await ev(() => document.querySelector('.rpg-trade-collect')?.click());
await page.waitForTimeout(1500);
console.log('after collect:', pick(await inv()));
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
