import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const r4 = fs.readFileSync(`${S}/demo/r4.txt`, 'utf8');
const withDirector = lines => r4.replace(/<Director>[\s\S]*?<\/Director>/, `<Director>\n${lines}\n</Director>`);
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await h.turn(withDirector('+ quest Sheep-killer — kill the wolf | giver: Garrow | reward: 2 silver | step: track it\n+ quest Herb run — twelve moonleaf | giver: Mother Ysolde | reward: 5 copper'), 'I take both.');
await page.waitForTimeout(2000);
await h.turn(withDirector('~ Sheep-killer — step: wolf slain, reward collected'), 'We bring the head back.');
await page.waitForTimeout(2500);
const note = await ev(async () => { const ctx = SillyTavern.getContext(); await window.storyDirectorInterceptor(ctx.chat, 8000, () => {}, 'normal'); return ctx.extensionPrompts?.story_director?.value ?? ''; });
console.log('quest check line:', note.split('\n').find(l => l.startsWith('Quest check')) ?? 'none');
await h.tab('ext:story-director-quests'); await page.waitForTimeout(800);
console.log('buttons:', await ev(() => [...document.querySelectorAll('.story-director-quest-actions .menu_button')].map(b => b.textContent).join(', ')));
await ev(() => [...document.querySelectorAll('.story-director-record.is-quest')].find(n => /Herb run/.test(n.textContent)).querySelector('.story-director-quest-abandon').click()); await page.waitForTimeout(300);
await ev(() => [...document.querySelectorAll('.story-director-record.is-quest')].find(n => /Herb run/.test(n.textContent)).querySelector('.story-director-quest-abandon').click()); await page.waitForTimeout(2000);
console.log('finished:', await ev(() => [...document.querySelectorAll('.story-director-record.is-finished')].map(n => n.textContent).join(' | ')));
console.log('director block:', await ev(() => (SillyTavern.getContext().chat.at(-1).mes.match(/<Director>[\s\S]*?<\/Director>/) ?? [''])[0].replace(/\n/g, ' / ')));
await h.tab('ext:rpg-party'); await page.waitForTimeout(800);
console.log('rpg offers:', await ev(() => [...document.querySelectorAll('.rpg-battle-offer-text')].map(n => n.textContent).join(' || ') || 'none'));
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
