import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
const setup = await ev(() => { const c = SillyTavern.getContext(); const b = c.extensionSettings.storyBlock.blocks.find(x => x.template === 'inventory'); const was = b.enabled; b.enabled = true; c.saveSettingsDebounced(); return { was, updates: b.updates }; });
console.log('inventory block:', JSON.stringify(setup));
const base = fs.readFileSync(`${S}/demo/r3.txt`, 'utf8').replace(/<Encounter>[\s\S]*?<\/Encounter>/, '').replace('Waterskin | 1 | Half full', 'Waterskin | 1 | Half full\n\n[Consumables]\nMinor Healing Draught | 4 | heal 20');
await h.turn(base, 'I check my satchel.');
await page.waitForTimeout(2000);
const changes = base.replace(/<Inventory>[\s\S]*?<\/Inventory>/, '<Inventory_Changes>\n- Minor Healing Draught | 1\n[Loot]\n+ Brood-Mother Skull | 1 | uncommon material · MDEF\n~ Coin Pouch | 1 | 5 Silver, 8 Copper\n</Inventory_Changes>');
const at = await h.turn(changes, 'I drink one and pocket the skull.');
await page.waitForTimeout(3000);
const mes = await ev(i => SillyTavern.getContext().chat[i].mes, at);
console.log('changes tag left:', /Inventory_Changes/.test(mes));
console.log((mes.match(/<Inventory>[\s\S]*?<\/Inventory>/) ?? ['no Inventory'])[0]);
const shown = await ev(i => document.querySelector(`#chat .mes[mesid="${i}"] .mes_text`)?.innerText ?? '', at);
console.log('visible in narration:', /Inventory|Brood-Mother/.test(shown));
const viaApi = await ev(() => window.StoryBlock?.getBlock?.('Inventory')?.text ?? 'no api');
console.log('getBlock has skull:', /Brood-Mother Skull/.test(viaApi), '· draught 3:', /Minor Healing Draught \| 3/.test(viaApi));
// A quiet reply that changes nothing: the state carries on.
const quiet = base.replace(/<Inventory>[\s\S]*?<\/Inventory>/, '');
const q = await h.turn(quiet, 'I rest.');
await page.waitForTimeout(2500);
const qm = await ev(i => SillyTavern.getContext().chat[i].mes, q); console.log('quiet copy rows:', (qm.match(/<Inventory>[\s\S]*?<\/Inventory>/) ?? [''])[0].split('\n').filter(l => /Skull|Draught/.test(l)).join(' / '));
console.log('quiet reply has a copy:', await ev(i => /<Inventory>/.test(SillyTavern.getContext().chat[i].mes), q), '· state still has skull:', /Brood-Mother/.test(await ev(() => window.StoryBlock.getBlock('Inventory')?.text ?? '')));
const toasts = await ev(() => [...document.querySelectorAll('.toast-message')].map(t => t.textContent).join(' | '));
console.log('toasts:', toasts || 'none');
await ev(w => { const c = SillyTavern.getContext(); c.extensionSettings.storyBlock.blocks.find(x => x.template === 'inventory').enabled = w; c.saveSettingsDebounced(); }, setup.was);
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
