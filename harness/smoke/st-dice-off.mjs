import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-proxy-server'] });
const page = await browser.newPage({ viewport: { width: 900, height: 1000 } });
await page.goto('http://127.0.0.1:8123/', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.SillyTavern?.getContext?.()?.characters?.length > 0 && window.StoryBlock?.apiVersion === 1 && window.StorySuite, null, { timeout: 60000 });
await page.waitForTimeout(4500);
const ev = (fn, a) => page.evaluate(fn, a);
await ev(async () => { const ctx = SillyTavern.getContext(); await ctx.selectCharacterById(String(ctx.characters.findIndex(c => c.name === 'Seraphina'))); });
await page.waitForTimeout(3000);
const prompt = () => ev(async () => { const ctx = SillyTavern.getContext(); await window.storyBlockGenerationInterceptor(ctx.chat, 8000, () => {}, 'normal'); const v = ctx.extensionPrompts?.story_block?.value ?? ''; return { has: window.StorySuite.has('rpg-battle'), notes: (v.match(/Never roll a fight[^\n]*/g) || []).length, dice: (v.match(/This reply's rolls/g) || []).length, blocks: ctx.extensionSettings.storyBlock.blocks.filter(b => /dice/.test(b.id)).map(b => b.id + ':' + b.enabled + ':' + b.display + ':' + b.template + ':' + JSON.stringify(b.rolls)).join(' ') }; });
const set = on => ev(v => window.StorySuite.providers().find(p => p.id === 'rpg-battle').api.manage.setEnabled(v), on);
console.log('start:', JSON.stringify(await prompt()));
await set(true); await page.waitForTimeout(500);
console.log('on:', JSON.stringify(await prompt()));
await set(false); await page.waitForTimeout(500);
console.log('off:', JSON.stringify(await prompt()));
await set(true); await page.waitForTimeout(800);
console.log('on again:', JSON.stringify(await prompt()));
await browser.close();
