import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const OUT = `${S}/uiux/use-now`;
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const base = fs.readFileSync(`${S}/demo/r3.txt`, 'utf8').replace(/<Encounter>[\s\S]*?<\/Encounter>/, '')
  .replace('Waterskin | 1 | Half full', 'Waterskin | 1 | Half full\n\n[Consumables]\nMinor Healing Draught | 2 | heal 20');
const pane = () => ev(() => { const p = [...document.querySelectorAll('.story-block-pane')].find(n => n.style.display !== 'none'); return (p?.innerText ?? '').replace(/\s+/g, ' ').slice(0, 400); });
const partyHp = () => ev(() => (SillyTavern.getContext().chat.at(-1).mes.match(/HP: \d+\/\d+/) ?? ['?'])[0]);
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await h.turn(base, 'I look around.');
await page.waitForTimeout(2000);
await h.turn(base + `\n<Wounds>\nRen — grave wound: a fall into the weir\n</Wounds>`, 'I slip.');
await page.waitForTimeout(2500);
await h.tab('ext:rpg-party'); await page.waitForTimeout(800);
console.log('party page before:', await pane());
console.log('block before:', await partyHp());
await h.click('^Use item'); await page.waitForTimeout(800);
await ev(() => [...document.querySelectorAll('.rpg-battle-use')].find(n => n.offsetParent)?.click()); await page.waitForTimeout(1500);
console.log('block after use:', await partyHp());
console.log('items page after:', await pane());
await h.click('^Back'); await page.waitForTimeout(1000);
console.log('party page after Back:', await pane());
await page.screenshot({ path: `${OUT}/4-party-after.png` });
await h.tab('ext:rpg-battle'); await page.waitForTimeout(1000);
console.log('battle tab after:', await pane());
await page.screenshot({ path: `${OUT}/5-battle-after.png` });
await ev(() => document.querySelector('.story-block-sidebar-tab[data-tab-id="party"]')?.click()); await page.waitForTimeout(800);
console.log('SB party tab:', await pane());
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
