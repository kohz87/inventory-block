import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const r4 = fs.readFileSync(`${S}/demo/r4.txt`, 'utf8');
const at = (time, lines) => r4.replace('1203, March 3, 09:50 am', time).replace(/<Director>[\s\S]*?<\/Director>/, `<Director>\n${lines}\n</Director>`);
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
const note = () => ev(async () => { const ctx = SillyTavern.getContext(); ctx.chat.push({ name: ctx.name1, is_user: true, is_system: false, mes: 'Go on.', extra: {} }); await window.storyDirectorInterceptor(ctx.chat, 8000, () => {}, 'normal'); const v = ctx.extensionPrompts?.story_director?.value ?? ''; ctx.chat.pop(); return v; });
await h.turn(at('CY 611, Goldwane 3, 10:00 am', '+ beat Mill fire — the old mill burns | on: Goldwane 4, 08:00 pm | place: Harrowford | reach: flour doubles in price; the miller begs Ren for help\n+ beat Toll riders — riders block the ford | on: Goldwane 3, 11:00 am | place: the ford\n+ hook Wolf Hunt — wolves at the east fold | step: tracking'), 'I rest at the inn.');
await page.waitForTimeout(1500);
// Days pass: the mill fire comes due in the gap.
await h.turn(at('CY 611, Goldwane 6, 07:00 am', '! Fold Wolf Hunts — the pack was seen at dawn'), 'I sleep for days.');
await page.waitForTimeout(2500);
const n = await note();
console.log('While away:', n.split('\n').find(l => l.startsWith('While away')) ?? 'none');
console.log('Slipped:', n.split('\n').find(l => l.startsWith('Slipped')) ?? 'none');
console.log('director block of last reply:', await ev(() => (SillyTavern.getContext().chat.at(-1).mes.match(/<Director>[\s\S]*?<\/Director>/) ?? [''])[0].replace(/\n/g, ' / ')));
await h.turn(at('CY 611, Goldwane 6, 08:00 am', '! Fold Wolf Hunts — tracks by the river'), 'I follow the tracks.');
await page.waitForTimeout(2000);
await h.tab('ext:story-director'); await page.waitForTimeout(600);
console.log('warnings:', await ev(() => [...document.querySelectorAll('.story-block-pane')].find(n => n.style.display !== 'none')?.innerText.match(/Warnings[\s\S]{0,120}/)?.[0]?.replace(/\n/g, ' | ') ?? 'none'));
await h.tab('ext:story-director-journal'); await page.waitForTimeout(800);
const tabs = await ev(() => [...document.querySelectorAll('.story-block-sidebar-tab')].map(t => t.dataset.tabId).join(', '));
console.log('tabs:', tabs);
console.log('journal:', await ev(() => [...document.querySelectorAll('.story-block-pane')].find(n => n.style.display !== 'none')?.innerText.slice(0, 400).replace(/\n+/g, ' | ')));
await page.locator('#story_block_sidebar').screenshot({ path: `${S}/shots/journal.png` });
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
