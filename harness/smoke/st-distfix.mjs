import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const pack = fs.readFileSync(`${S}/smoke/pack.json`, 'utf8');
const r4 = fs.readFileSync(`${S}/demo/r4.txt`, 'utf8');
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await ev(p => { SillyTavern.getContext().extensionSettings.storyDirector.worldPack = p; }, pack);
const scene = r4.match(/<World_State>[\s\S]*?<\/World_State>/)[0].replace(/\*\*🌤 Loc:\*\*[^|]*\|[^|]*\|/, '**🌤 Loc:** Bluewatch Village | Adventurer Guild Branch |').replace('1203, March 3, 09:50 am', 'CY 611, Goldwane 12, 01:10 pm');
const prose = '"The board\'s thin today," Verna added. "And the ferryman at Ledgerford sent word about river-leeches fouling the haul-chains, but that\'s three days downstream."';
const reply = r4.replace(/^[\s\S]*?(<!-- STORY_BLOCKS_V1)/, `${prose}\n\n$1`).replace(/<World_State>[\s\S]*?<\/World_State>/, scene);
await h.turn(reply, 'I check the board.');
await page.waitForTimeout(2500);
const toast = await ev(() => [...document.querySelectorAll('#toast-container .toast')].map(t => t.innerText.replace(/\s+/g, ' ')).find(t => /by the map/.test(t)) ?? 'none');
console.log('toast:', toast);
await h.tab('ext:story-director'); await page.waitForTimeout(600);
console.log('warnings in tab:', await ev(() => ([...document.querySelectorAll('.story-block-pane')].find(n => n.style.display !== 'none')?.innerText.match(/by the map[^\n]*/) ?? ['none'])[0]));
await page.locator('.story-director-fix-distance').first().click();
await page.waitForTimeout(1500);
console.log('reply now:', await ev(() => (SillyTavern.getContext().chat.at(-1).mes.match(/but that[^"]*"/) ?? ['?'])[0]));
console.log('shown now:', await ev(() => (document.querySelector('#chat .mes.last_mes .mes_text')?.innerText.match(/but that[^"”]*/) ?? ['?'])[0]));
await page.waitForTimeout(1500);
// Saved: read the chat file back.
const file = fs.readFileSync(`${S}/st/app/data/default-user/chats/The Narrator/The Narrator - 2026-10-18@09h00m00s000ms.jsonl`, 'utf8');
console.log('saved with fix:', /twenty-one days downstream|days downstream/.test(file) && !/three days downstream/.test(file.split('\n').at(-1) || file.split('\n').at(-2)));
await ev(() => { delete SillyTavern.getContext().extensionSettings.storyDirector.worldPack; });
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
