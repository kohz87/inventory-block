import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const read = f => fs.readFileSync(`${S}/demo/${f}`, 'utf8');
const side = file => page.screenshot({ path: `${S}/shots/${file}.png`, clip: { x: 1090, y: 40, width: 350, height: 950 } });
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await h.tab('ext:rpg-party'); await page.waitForTimeout(800);
console.log('card before:', await ev(() => [...document.querySelectorAll('.rpg-battle-member-card[data-member-id="pc"] .rpg-battle-skill')].map(n => n.querySelector('.rpg-battle-record-name').textContent + ' [' + n.querySelector('.rpg-battle-mastery')?.textContent + ' | ' + n.querySelector('.rpg-battle-mastery')?.title + ']').join('; ')));
await h.turn(read('r3.txt'), 'We take the river path east to the weir.');
await page.waitForTimeout(3000);
await h.tab('ext:rpg-battle'); await page.waitForTimeout(800);
console.log('fight:', await h.click('^Fight')); await page.waitForTimeout(3000);
console.log('start:', await h.click('^Start')); await page.waitForTimeout(1500);
for (let i = 0; i < 24; i++) { if (!(await h.click('^Auto'))) break; await page.waitForTimeout(1200); }
const gains = await ev(() => [...document.querySelectorAll('.rpg-battle-gains dt')].map((dt, i) => `${dt.textContent}: ${document.querySelectorAll('.rpg-battle-gains dd')[i].textContent}`));
console.log('gains:', JSON.stringify(gains));
await ev(() => document.querySelector('.rpg-battle-section.is-gains')?.scrollIntoView());
await side('rpg-mastery-result');
await h.click('^Return to story'); await page.waitForTimeout(1500);
await h.tab('ext:rpg-party'); await page.waitForTimeout(800);
console.log('card after:', await ev(() => [...document.querySelectorAll('.rpg-battle-member-card[data-member-id="pc"] .rpg-battle-skill')].map(n => n.querySelector('.rpg-battle-record-name').textContent + ' [' + n.querySelector('.rpg-battle-mastery')?.textContent + ']').join('; ')));
await ev(() => document.querySelector('.rpg-battle-member-card[data-member-id="pc"] .rpg-battle-card-skills')?.scrollIntoView());
await side('rpg-mastery-card');
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
