import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-proxy-server'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const logs = []; page.on('console', m => { if (/Story Block|error/i.test(m.text())) logs.push(m.type() + ': ' + m.text()); });
await page.goto('http://127.0.0.1:8123/', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.SillyTavern?.getContext?.()?.characters?.length > 0 && window.StoryBlock?.apiVersion === 1, null, { timeout: 60000 });
await page.evaluate(async () => { const ctx = SillyTavern.getContext(); await ctx.selectCharacterById(String(ctx.characters.findIndex(c => c.name === 'Seraphina'))); });
await page.waitForFunction(() => SillyTavern.getContext().chat?.length > 0, null, { timeout: 20000 });
await page.waitForTimeout(1000);
const out = await page.evaluate(async () => {
  const sb = window.StoryBlock; const ctx = SillyTavern.getContext();
  const r = {};
  r.version = sb.version;
  r.register = sb.registerBlock({ id: 'story-director', tag: 'Director', name: 'Story Director' });
  r.dup = sb.registerBlock({ id: 'x', tag: 'World_State' });
  r.list = sb.listBlocks().map(b => b.tag).join(',');
  const replies = [];
  sb.onReply(p => replies.push(p.messageIndex));
  const i = ctx.chat.length - 1;
  ctx.chat[i].mes = 'The courier rode out at dawn.\n<Director>\n+ agenda Courier — now: rides south | on: Haywane 13\n</Director>';
  await ctx.eventSource.emit(ctx.eventTypes.MESSAGE_RECEIVED, i);
  await new Promise(res => setTimeout(res, 500));
  r.wrapped = /STORY_BLOCKS_V1/.test(ctx.chat[i].mes);
  r.rendered = document.querySelector(`#chat .mes[mesid="${i}"] .mes_text`)?.textContent.trim();
  r.getBlock = sb.getBlock('Director')?.text;
  r.inText = sb.blockInText(ctx.chat[i].mes, 'Director')?.text;
  r.replies = replies;
  r.ws = sb.getBlock('World_State')?.messageIndex;
  r.set = await sb.setBlockText(i, 'Director', '+ agenda Courier — now: rides south | on: Haywane 13\n~ Courier — then: delivers the writ');
  r.afterSet = sb.blockForGeneration('Director', 'normal')?.text;
  r.swipeView = sb.blockForGeneration('Director', 'swipe')?.messageIndex ?? null;
  return r;
});
console.log(JSON.stringify(out, null, 1));
console.log(logs.slice(-5).join('\n'));
await browser.close();
