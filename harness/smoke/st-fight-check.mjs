import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const logs = [];
page.on('console', m => { if (/RPG Battle|error|Error/i.test(m.text())) logs.push(`${m.type()}: ${m.text()}`); });
const r3 = fs.readFileSync(`${S}/demo/r3.txt`, 'utf8');
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await h.turn(r3, 'We take the river path east to the weir.');
await page.waitForTimeout(3000);
await h.tab('ext:rpg-battle'); await page.waitForTimeout(800);
console.log('battle pane:', (await h.pane()).slice(0, 300));
console.log('fight click:', await h.click('^Fight')); await page.waitForTimeout(3000);
console.log('after fight:', (await h.pane()).slice(0, 300));
console.log('start click:', await h.click('^Start')); await page.waitForTimeout(2000);
console.log('after start:', (await h.pane()).slice(0, 300));
console.log('logs:', logs.slice(0, 10).join('\n') || 'none');
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
