import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const OUT = `${S}/uiux/sd-after`;
const size = process.argv[2] === 'mobile' ? { width: 390, height: 844 } : { width: 1440, height: 1000 };
const tag = process.argv[2] === 'mobile' ? 'mobile' : 'desktop';
const h = await open(size);
const { page, ev } = h;
const r4 = fs.readFileSync(`${S}/demo/r4.txt`, 'utf8').replace(/<XP>[\s\S]*?<\/XP>\n?/, '');
const at = (time, lines) => r4.replace('1203, March 3, 09:50 am', time).replace(/<Director>[\s\S]*?<\/Director>/, `<Director>\n${lines}\n</Director>`);
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
const beats = ['Mill fire', 'Ferry strike', 'Bell tolls', 'Wolves at the ford', 'Salt riot', 'Toll raised', 'Café burned', 'Bridge washed out', 'Heron sighted', 'Pilgrims arrive'];
await h.turn(at('CY 611, Goldwane 10, 08:00 am', beats.map(b => `+ event ${b} — it may happen | on: Goldwane 10, 06:00 pm`).join('\n')), 'I look around.');
await page.waitForTimeout(1500);
await h.turn(at('CY 611, Goldwane 10, 07:00 pm', beats.map(b => `! ${b} — it happened before the crowd`).join('\n')), 'I watch.');
await page.waitForTimeout(1500);
await h.turn(at('CY 611, Goldwane 11, 09:00 am', beats.slice(0, 6).map(b => `- ${b} — over`).join('\n') + '\n+ hook Lime Kiln Bats — Clear the bats in the old kiln | giver: Elke | reward: 5 silver\n+ hook Reed-Bed Hogs — Cull three river hogs | giver: Reeve Hollis | reward: 3 silver'), 'Any work?');
await page.waitForTimeout(2500);
if (tag === 'mobile') await ev(() => document.querySelector('#story_block_handle')?.click());
await h.tab('ext:story-director-journal'); await page.waitForTimeout(900);
console.log('entries:', await ev(() => document.querySelectorAll('.story-director-journal .story-director-record').length), 'search box:', await ev(() => Boolean(document.querySelector('.story-director-journal-search'))));
await page.screenshot({ path: `${OUT}/${tag}-journal.png` });
await page.locator('.story-director-journal-search').fill('cafe');
await page.waitForTimeout(400);
console.log('after "cafe":', await ev(() => [...document.querySelectorAll('.story-director-journal .story-director-record-key')].map(n => n.textContent).join(', ')), '·', await ev(() => document.querySelector('.story-director-journal-count')?.textContent), '· focus kept:', await ev(() => document.activeElement?.classList.contains('story-director-journal-search')));
await page.screenshot({ path: `${OUT}/${tag}-journal-search.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
console.log('after Esc:', await ev(() => document.querySelector('.story-director-journal-search')?.value === ''), await ev(() => document.querySelectorAll('.story-director-journal .story-director-record').length));
console.log('quests badge:', await ev(() => [...document.querySelectorAll('.story-block-tab, [data-tab-id], button')].filter(n => /Quests/.test(n.textContent)).map(n => n.textContent.replace(/\s+/g, ' ').trim()).slice(0, 3).join(' | ')));
await page.screenshot({ path: `${OUT}/${tag}-quests-badge.png` });
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
