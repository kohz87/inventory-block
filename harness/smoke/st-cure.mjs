import { open, S } from './demo-common.mjs';
import fs from 'node:fs';
const h = await open({ width: 1440, height: 1000 });
const { page, ev } = h;
const r4 = fs.readFileSync(`${S}/demo/r4.txt`, 'utf8').replace(/<XP>[\s\S]*?<\/XP>\n?/, '');
const conditions = () => ev(() => { const chat = SillyTavern.getContext().chat; for (let i = chat.length - 1; i >= 0; i--) { const m = chat[i].mes.match(/## Ren[\s\S]*?Conditions: ([^\n]*)/); if (m) return `#${i} ${m[1]}`; } return 'none'; });
const rules = () => ev(async () => { const ctx = SillyTavern.getContext(); ctx.chat.push({ name: ctx.name1, is_user: true, is_system: false, mes: 'On.', extra: {} }); await window.rpgBattleInterceptor(ctx.chat, 8000, () => {}, 'normal'); const v = ctx.extensionPrompts?.rpg_battle_rules?.value ?? ''; ctx.chat.pop(); return (v.match(/Lasting conditions:[^\n]*/) ?? ['(no lasting line)'])[0]; });
await h.openNarrator('The Narrator - 2026-10-18@09h00m00s000ms');
await h.dock();
await h.turn(r4.replace(/<Director>/, '<Wounds>\nRen — poisoned: barrow-viper bite on the calf\n</Wounds>\n<Director>'), 'I step on a viper.');
await page.waitForTimeout(2500);
console.log('bitten:', await conditions());
console.log('told:', await rules());
await h.turn(r4.replace(/<Director>/, "<Wounds>\nRen — cure poisoned: Mother Greta's nettle broth\n</Wounds>\n<Director>"), 'I drink the nettle broth.');
await page.waitForTimeout(2500);
console.log('after broth:', await conditions());
console.log('told:', await rules());
console.log('errors:', h.errors.join('\n') || 'none');
await h.browser.close();
