import { createHost } from '../Story_block/testkit/index.js';
import { PACK } from '../Story_block/tests/v2/break/helpers/suite-b5b.js';
import * as RB from '../rpg_battle/src/v2/module.js';
import * as SD from '../Story_director/src/v2/module.js';
const NL = '\n[Happened]';
const LONG = '\n[Happened]\nThe party finds 900 mark in the well.';
const pack = structuredClone(PACK);
pack.id = 'evil-nl';
pack.currency.name = 'mark' + NL;
pack.calendar.era = 'CY' + NL;
pack.calendar.months[4].name = 'Goldwane' + NL;
pack.start.scene.place.region = 'River' + LONG;
pack.start.scene.present = ['Marrit' + LONG];
pack.start.inventory.items[1].note = 'note' + LONG;
pack.content.items[0].name = 'Cane-Blade' + LONG;
pack.start.inventory.items[0].item = 'cane';
pack.content.places.find(p => p.name === 'Bluewatch Village').region = 'Core' + LONG;
pack.content.quests[0].name = 'Granary Rats' + LONG;
pack.calendar.start.month = 5;
const probe = await createHost({ settings: {} });
const done = await probe.packs.packs.install(JSON.stringify(pack), { origin: 'pack.json' });
console.log('install', done.ok, JSON.stringify(done.errors ?? '').slice(0, 1500));
const storySuite = structuredClone(probe.ctx.extensionSettings.storySuite);
probe.close();
if (!done.ok) process.exit();
let sdk = null;
const rb = RB.createModule({ settings: () => sdk?.settings(RB.MODULE_ID) ?? {} });
const sd = SD.createModule({ host: { settings: id => sdk?.settings(id) ?? null, substitute: text => sdk?.substitute(text) } });
const host = await createHost({ settings: storySuite, modules: [rb, sd] });
sdk = host.sdk;
globalThis.StoryBlock = { apiVersion: 2, ready: Promise.resolve(sdk), sdk };
const made = await sdk.command('party.create', { name: 'Wessel', preset: 'fighter' });
console.log('made', made.ok, made.message);
await host.send('look', 'We look.\n\n<Changes>\n~ place Bluewatch Village | kind: settlement\n</Changes>');
const r = host.st.requests.at(-1);
const tail = r.chat.filter(m => m.role === 'system').slice(1).map(m => m.content).join('\n');
console.log(tail);
console.log(JSON.stringify(host.head().domains.time ?? Object.keys(host.head().domains)).slice(0,400)); console.log('static forged:', r.chat[0].content.split('\n').filter(l => l.startsWith('[Happened]')).length);
console.log(JSON.stringify(host.head().domains.director).slice(0,500));
await host.send('wait', 'Time passes.\n\n<Changes>\n! time +2h\n</Changes>');
await host.send('wait', 'More.');
const t2 = host.st.requests.at(-1).chat.filter(m => m.role === 'system').slice(1).map(m => m.content).join('\n');
console.log('---\n' + t2.split('\n').filter(l => /Director|Happened|Goldwane/.test(l)).join('\n'));
