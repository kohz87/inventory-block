import { suiteHost, withParty, seedCrypto } from './suite-host.mjs';
console.warn = () => {};
seedCrypto(5);
const lines = process.argv.slice(2);
const host = await suiteHost();
await withParty(host);
await host.send('hi', 'Hello.');
await host.send('go', host.reply('Story.', lines));
const d = host.head().domains;
for (const t of Object.values(d.director.threads)) console.log('THREAD', JSON.stringify(t).slice(0, 600), 'len', JSON.stringify(t).length);
console.log('KEYS', JSON.stringify(d.director.keys ?? {}).slice(0, 300));
console.log('chron', JSON.stringify(d.chronicle).slice(0, 500));
console.log('atlas', JSON.stringify(d.atlas).slice(0, 500));
console.log('inv', JSON.stringify(d.inventory).slice(0, 600));
console.log('scene', JSON.stringify(d.scene).slice(0, 300));
for (const p of host.turn.problems()) console.log('P', p.code, p.message.slice(0, 220));
for (const p of d.director.problems) console.log('DP', JSON.stringify(p).slice(0, 220));
await host.send('next', 'ok');
console.log('TAIL', host.tails().at(-1).length, '\n' + host.tails().at(-1).slice(0, 1500));
