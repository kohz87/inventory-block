import { launch, openPage, openNarrator, queue, clearQueue, chatId, cmd, idle, sendText, sleep, uiState, setStream, J } from './lib.mjs';
const errors = [];
const browser = await launch();
const page = await openPage(browser, { errors });
await openNarrator(page);
const main = await chatId(page);
await cmd(page, 'party.create', { name: 'Ren', preset: 'fighter' });
await setStream(page, true);
clearQueue(); queue(`[R1] ${'Rain on roofs. '.repeat(300)}\n<Changes>\n+ item Rope\n</Changes>`);
await sendText(page, 'Long one.');
await sleep(700);
console.log('mid', J(await uiState(page)));
await page.reload({ waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.SillyTavern?.getContext?.()?.characters?.length > 0 && window.StoryBlock?.apiVersion === 2, null, { timeout: 90000 });
await sleep(1500);
console.log('after reload (welcome)', J(await uiState(page)));
await page.evaluate(async c => { const ctx = SillyTavern.getContext(); const id = ctx.characters.findIndex(x => x.name === 'The Narrator'); await ctx.selectCharacterById(String(id)); await new Promise(r => setTimeout(r, 1500)); await ctx.openCharacterChat(c); }, main);
await sleep(2000);
console.log('chat reopened', J(await uiState(page)));
await sleep(5000);
console.log('5 s later', J(await uiState(page)));
console.log(errors.filter(e => !/404|No message/.test(e)).slice(0, 5));
await browser.close();
