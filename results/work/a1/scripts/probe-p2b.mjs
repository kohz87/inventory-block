// Pass 2 directed: loot taken on a later reply, then the loot reply deleted; equipOn to a companion then delete/swipe.
import { allHost, storeMod, seededMod } from './lib/host.mjs';
const restore = seededMod.seedCrypto(12);
console.warn = () => {};
const h = await allHost({ pack: true, nsdSettings: true });
const { sdk, store, st, ctx } = h;
const J = v => JSON.stringify(v);
const fresh = () => { const snap = JSON.parse(JSON.stringify(ctx.chat)); return storeMod.createStore({ chat: () => snap, save: async () => {}, validate: (s, n) => n.flatMap(x => { const f = h.registry.validator(x); return f ? (f(s?.domains?.[x], s) ?? []).map(String) : []; }), scratch: n => h.registry.scratch(n) }).head(); };
const cmp = label => { const a = store.head(), b = fresh(); console.log(label.padEnd(30), J(a) === J(b) ? 'ok' : 'MISMATCH', 'rev', a?.meta?.rev, 'items', Object.values(a.domains.inventory.stacks).map(s => a.domains.inventory.defs[s.def].name + (s.owner !== 'party' ? '@' + s.owner : '') + (s.equipped ? '*' : '')).join(',')); };
const R = (t, lines) => `${t}\n<Changes>\n${lines.join('\n')}\n</Changes>`;
const c = async (t, p) => { const r = await sdk.command(t, p); console.log('  ', t, r.ok ? 'ok' : `${r.code} ${r.message}`.slice(0, 140)); return r; };
await c('party.create', { name: 'Ren', preset: 'fighter' });
await h.send('a', R('a', ['+ join Fenna — a ranger | level: 1 | role: scout']));
const offer = Object.keys(store.head().domains.party.offers ?? {})[0];
await c('party.acceptOffer', { offer });
await h.send('b', R('b', ['? loot Spear, Iron Cap — on the floor']));
cmp('loot laid');
await h.send('c', R('c', ['+ coin 2 | from: Kael']));
const sid = Object.keys(store.head().domains.inventory.loot ?? {})[0];
await c('inventory.lootTake', { sid, pick: [0, 1] });
cmp('taken on reply c');
const fenna = Object.values(store.head().domains.party.actors).find(a => a.name === 'Fenna')?.id;
const spear = Object.values(store.head().domains.inventory.stacks).find(s => /spear/.test(s.def));
await c('inventory.equipOn', { stack: spear.id, actor: fenna });
cmp('spear on Fenna');
await h.send('d', R('d', ['~ item Spear | wear: tear']));
cmp('spear worn');
const b = ctx.chat.findIndex(m => /^b\n/.test(m.mes ?? ''));
await st.deleteMessage(b); await st.deleteMessage(b - 1);
cmp('loot reply deleted');
await st.deleteMessage(ctx.chat.length - 1); cmp('delete last');
await h.regenerate(R('c2', ['+ coin 1 | from: Kael'])); cmp('regenerate c');
restore(); h.close(); process.exit(0);
