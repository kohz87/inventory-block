import fs from 'node:fs';
import { launch, waitHost, connect, ST_URL, shot, j } from './common.mjs';
import { openChat } from './lib-ui.mjs';
const { chat } = JSON.parse(fs.readFileSync(new URL('./chat.json', import.meta.url)));
const W = Number(process.env.W ?? 390);
const { browser, page, errors } = await launch({ width: W, height: W < 600 ? 844 : 900, mobile: W < 600 });
await page.goto(ST_URL, { waitUntil: 'domcontentloaded' });
await waitHost(page); await connect(page); await openChat(page, chat);
await page.click('.story-suite-bar-settings');
await page.waitForSelector('#story_suite_v2_overlay');
await page.waitForTimeout(500);
const info = () => page.evaluate(() => [...document.querySelectorAll('#story_suite_v2_overlay details.story-suite-fold')].map(d => { const body = d.querySelector(':scope > :not(summary)'); return `${d.dataset.fold}:open=${d.open}:h=${Math.round(d.getBoundingClientRect().height)}:body=${body ? Math.round(body.scrollHeight) + '/' + Math.round(body.getBoundingClientRect().height) + ' ov=' + getComputedStyle(body).overflow + ' mh=' + getComputedStyle(body).maxHeight : '-'}`; }));
console.log('initial', j(await info()));
await page.click('#story_suite_v2_overlay details[data-fold="story-suite-features"] > summary');
await page.waitForTimeout(1200);
console.log('after click features', j(await info()));
await shot(page, `w${W}-overlay-features-click`);
await page.click('#story_suite_v2_overlay details[data-fold="story-block"] > summary');
await page.waitForTimeout(1200);
console.log('after click story-block', j(await info()));
await page.locator('#story_suite_v2_overlay details[data-fold="story-block"]').scrollIntoViewIfNeeded();
await shot(page, `w${W}-overlay-sb-click`);
await browser.close();
